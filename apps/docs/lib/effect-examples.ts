/** The next effect in reading order (no wrap, like the upstream head nav). */
export const nextEffect = (slug: string) => {
  const i = EFFECTS.findIndex((e) => e.slug === slug);
  return i < 0 || i >= EFFECTS.length - 1 ? undefined : EFFECTS[i + 1];
};

/** The previous effect in reading order. */
export const prevEffect = (slug: string) => {
  const i = EFFECTS.findIndex((e) => e.slug === slug);
  return i <= 0 ? undefined : EFFECTS[i - 1];
};
